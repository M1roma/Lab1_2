#include <stdio.h>  //підключення стандартних бібліотек
#include <stdlib.h>
#include <math.h>

int main() {
    // =========================================================================
    // ОГОЛОШЕННЯ ЗМІННИХ ТА ПОЯСНЕННЯ ТИПІВ ДАНИХ!                            |
    // =========================================================================

    // mode — номер варіанта введення (1 або 2).
    // Тип int - ціле число.
    int mode = 0;

    // x1 — початок інтервалу, x2 — кінець інтервалу, delta — крок зміни аргументу.
    // Тип double — дійсне число з плаваючою крапкою.
    double x1 = 0.0;
    double x2 = 0.0;
    double delta = 0.0;

    // n — кількість точок у таблиці розрахунку.
    // Тип unsigned int — ціле беззнакове число
    // Кількість точок не може бути від'ємною, тому за вимогами використовуємо unsigned int.
    unsigned int n = 0;

    // =============================================================================
    //  ВИБІР РЕЖИМУ ВВЕДЕННЯ З ПЕРЕВІРКОЮ ЧЕРЕЗ ОПЕРАТОР РОЗГАЛУДЖЕННЯ IF - ELSE
    // =============================================================================

    // додаємо оператор while(нескінченний цикл)
    while (1) {
        printf("Select input mode (1 or 2): ");

        // Якщо ввели не число (scanf поверне 0, тобто не 1)
        if (scanf("%d", &mode) != 1) {
            printf("Error! Not a number.\n\n");
            fflush(stdin); // Очищаємо буфер введення від некоректних символів
        }
        // Якщо ввели саме 1 або 2 — це правильний вибір, виходимо з циклу
        else if (mode == 1 || mode == 2) {
            break;
        }
        // Якщо ввели число, але не 1 і не 2 (наприклад, 5)
        else {
            printf("Error! Please select 1 or 2.\n\n");
        }
    }

    // =========================================================================
    //  ВВЕДЕННЯ ПАРАМЕТРІВ ТА РОЗРАХУНОК ВІДСУТНЬОГО ЗНАЧЕННЯ
    // =========================================================================

    // додаємо оператор while(нескінченний цикл)
    while (1) {
        // Режим 1: Введення X1, X2 та кількості точок N
        if (mode == 1) {
            printf("\nEnter X1, X2, N (X1 < X2 and N > 1):\n");
            printf("X1 = "); scanf("%lf", &x1); // %lf — зчитування типу double (з плаваючою крапкою)
            printf("X2 = "); scanf("%lf", &x2);
            printf("N  = "); scanf("%u", &n);   // %u — зчитування типу unsigned int (ціле без знакове число)

            if (x1 >= x2) {
                printf("Error! X1 must be less than X2.\n");
            }
            else if (n <= 1) {
                printf("Error! N must be greater than 1.\n");
            }
            else {
                // Обчислюємо крок delta за формулою для 1-го варіанта
                delta = (x2 - x1) / (n - 1);
                break; // Якщо всі данні правильні, виходимо з циклу
            }
        }
        // Режим 2: Введення X1, X2 та кроку delta
        else if (mode == 2) {
            printf("\nEnter X1, X2, delta (X1 < X2 and delta > 0):\n");
            printf("X1    = "); scanf("%lf", &x1);
            printf("X2    = "); scanf("%lf", &x2);
            printf("delta = "); scanf("%lf", &delta);

            if (x1 >= x2) {
                printf("Error! X1 must be less than X2.\n");
            }
            else if (delta <= 0) {
                printf("Error! delta must be greater than 0.\n");
            }
            else {
                // Обчислюємо кількість точок N за формулою для 2-го варіанта
                n = (unsigned int)((x2 - x1) / delta) + 1;
                break; // Якщо усі дані вірні, виходимо з циклу
            }
        }
    }

    
return 0;
}
